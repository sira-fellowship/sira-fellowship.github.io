"""Build evidence/census.js from the literature census (~/Developer/sira-literature-census).

Usage: python3 tools/census_data.py path/to/sira-literature-census/data/analysis.json

The census searches Semantic Scholar for social science papers on AI and its societal effects,
and Claude classifies each against SIRA's definition; analyze.py there writes analysis.json.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EMPIRICAL = {"experiment", "survey", "observational_data", "qualitative"}


def main(src):
    a = json.loads(Path(src).read_text())
    years = [str(y) for y in range(2015, 2027)]
    out = {
        "years": [int(y) for y in years],
        "papers": [a["by_year"][y] for y in years],
        "empiricalByYear": [a["empirical_by_year"][y] for y in years],
        "empiricalShare": [a["empirical_share_by_year"][y] for y in years],
        "meets": a["meets"],
        "classified": a["classified"],
        "empirical": a["empirical_total"],
        "experiments": a["experiment_total"],
        "threatModels": {k: v for k, v in a["threat_model_total"].items() if k != "not_applicable"},
        "threatModelStats": {
            k: {
                "papers": n,
                "y2019": a["threat_model_by_year"][k]["2019"],
                "y2025": a["threat_model_by_year"][k]["2025"],
                "empirical": sum(c for m, c in a["method_by_threat_model"][k].items() if m in EMPIRICAL),
                "experiments": a["method_by_threat_model"][k].get("experiment", 0),
            }
            for k, n in a["threat_model_total"].items() if k != "not_applicable"
        },
        "partialYear": 2026,
    }
    (ROOT / "evidence" / "census.js").write_text(
        "// Generated by tools/census_data.py from the SIRA literature census. Do not edit by hand.\n"
        "window.SIRA_CENSUS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    p = dict(zip(years, out["papers"]))
    print(f"meets {out['meets']:,}; 2019 {p['2019']:,} -> 2025 {p['2025']:,} ({p['2025'] / p['2019']:.1f}x); "
          f"empirical share 2019 {a['empirical_share_by_year']['2019']:.0%} -> 2025 {a['empirical_share_by_year']['2025']:.0%}")


if __name__ == "__main__":
    main(sys.argv[1])
